"""
Typed widget settings (widget "wcfg"), for type checking only

GENERATED by tools/gen_widget_config_types.py from widget default settings, do not edit.
Value types are what setting validation guarantees (see setting_validator.ValueValidator).
"""

from typing import Literal, TypedDict
