# Options added to every widget, plugins included (see template.setting_widget)
COMMON_DEFAULT = {"visibility_context": "Always", "stream_visibility": "Screen & Stream"}


def widget_defaults() -> dict[str, dict[str, Any]]:
    """Built-in widget default settings (plugins excluded), in display order"""
    from neopedal.template.setting_widget import WIDGET_DEFAULT
    from neopedal.template.widget import WIDGET_DISPLAY_ORDER

    return {name: WIDGET_DEFAULT[name] for name in WIDGET_DISPLAY_ORDER}


def class_name(widget_name: str) -> str:
    """TypedDict class name of widget"""
    return "".join(part.capitalize() for part in widget_name.split("_")) + "Config"


def alias_name(pattern: str) -> str:
    """Literal alias name of choice pattern, such as "^font_weight$" -> FontWeightChoice"""
    words = re.sub(r"[^a-z0-9_]", "", pattern.lower()).split("_")
    return "".join(word.capitalize() for word in words if word) + "Choice"


def validator_kind(key: str) -> str:
    """Name of first value validator that handles key (same order as preset validation)"""
    from neopedal.setting_validator import PresetValidator

    for validator in PresetValidator._value_validators:
        probe = {key: None}
        try:
            if validator(key, probe):
                return validator.__name__
        except TypeError:  # handled (validator reached value check)
            return validator.__name__
    raise RuntimeError(f"no validator for option: {key}")


def choice_list(key: str, kind: str) -> tuple[str, tuple[str, ...]] | None:
    """Choice pattern & choices of choice option, None if choices are not fixed"""
    from neopedal import regex_pattern as rxp

    choices = rxp.CHOICE_UNITS if kind == "choice_units" else rxp.CHOICE_COMMON
    for pattern, values in choices.items():
        if re.search(pattern, key):
            if isinstance(values, list):  # extended at runtime (languages)
                return None
            return pattern, tuple(values)
    return None


def value_type(key: str, default: Any, aliases: dict[str, tuple[str, ...]]) -> str:
    """Type of option value guaranteed by validation"""
    kind = validator_kind(key)
    if kind == "boolean":
        expected = "bool"
    elif kind in ("choice_units", "choice_common"):
        choice = choice_list(key, kind)
        if choice is None:
            expected = "str"
        else:
            pattern, values = choice
            name = alias_name(pattern)
            aliases[name] = values
            if default not in values:
                raise RuntimeError(f"default of {key} is not a valid choice: {default!r}")
            return name
    elif kind in ("color", "clock_format", "string"):
        expected = "str"
    elif kind == "integer":
        expected = "int"
    elif kind == "numeric":
        expected = "float"
    else:
        raise RuntimeError(f"unknown validator {kind} of option: {key}")
    actual = type(default).__name__
    if actual != expected and not (expected == "float" and actual == "int"):
        raise RuntimeError(f"default of {key} is {actual}, validation keeps {expected}")
    return expected


def common_keys(widgets: Mapping[str, Mapping[str, Any]]) -> list[str]:
    """Options of every widget, in order of first widget"""
    first, *others = widgets.values()
    return [key for key in first if all(key in options for options in others)]


def class_lines(name: str, base: str, doc: str, fields: Iterable[tuple[str, str]]) -> list[str]:
    lines = ["", "", f"class {name}({base}):", f'    """{doc}"""', ""]
    lines.extend(f"    {key}: {annotation}" for key, annotation in fields)
    if lines[-1] == "":
        lines[-1] = "    pass"  # pragma: no cover - every widget has own options
    return lines


def render() -> str:
    """Generated module source"""
    from neopedal.plugin_loader import PLUGIN_BASE_DEFAULT

    widgets = widget_defaults()
    aliases: dict[str, tuple[str, ...]] = {}
    types = {
        widget: {key: value_type(key, value, aliases) for key, value in options.items()}
        for widget, options in widgets.items()
    }
    plugin = {**PLUGIN_BASE_DEFAULT, **COMMON_DEFAULT}
    shared = [
        key for key in common_keys(widgets)
        if key in plugin and len({types[w][key] for w in types}) == 1
    ]
    first = next(iter(types.values()))
    body = class_lines(
        BASE_NAME, "TypedDict", "Options of every widget, plugins included", ((key, first[key]) for key in shared))
    shared_set = set(shared)
    for widget, fields in types.items():
        body.extend(class_lines(
            class_name(widget), BASE_NAME, f"{widget} widget",
            ((key, annotation) for key, annotation in fields.items() if key not in shared_set),
        ))
    body.extend(class_lines(
        PLUGIN_NAME, BASE_NAME, "Base options of plugin widgets (own options of each plugin not typed)",
        ((key, value_type(key, value, aliases)) for key, value in plugin.items() if key not in shared_set),
    ))
    alias_lines = [""]
    for name in sorted(aliases):
        values = ", ".join(f'"{value}"' for value in aliases[name])
        alias_lines.append(f"{name} = Literal[{values}]")
    footer = ["", "", "# Widget name -> TypedDict class", "WIDGET_CONFIG_TYPES: dict[str, type] = {"]
    footer.extend(f'    "{widget}": {class_name(widget)},' for widget in types)
    footer.append("}")
    return HEADER + "\n".join([*alias_lines, *body, *footer]) + "\n"


def main() -> None:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, OUTPUT), "w", encoding="utf-8", newline="\n") as file:
        file.write(render())
    print(f"written {OUTPUT}")


if __name__ == "__main__":
    main()
